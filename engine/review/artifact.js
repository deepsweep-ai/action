/**
 * S1.6 — shareable review artifact (markdown / HTML), a SANCTIONED render
 * module of the S1.9 choke point (tests/sanitize.test.ts guard).
 *
 * Two NEW escaping contexts beyond the terminal (norm 9):
 *
 *  - Markdown: the choke point already strips newlines (U+000A is inside the
 *    C0 range U+0000–U+001F), so no field can open a new line — heading and
 *    verdict forgery via embedded line breaks is impossible after the
 *    choke-point sanitizers (sanitizeField / sanitizeFieldKeepEnding — same
 *    strip set, S1.12). Markdown METAcharacters survive the strip set, though
 *    (`[`, `](…)`, `#`, `!`, `<`…), so every workspace-derived field is
 *    rendered inside a GFM code SPAN (mdCode below): link/image injection
 *    (`[x](javascript:…)`, `![x](…)`) and inline HTML are inert literal text
 *    inside a code span. Fields never start a line — every interpolation
 *    sits after a static prefix — so a field of backticks cannot open a
 *    fenced block either.
 *
 *  - HTML: every interpolated field passes the choke point AND escapeHtml
 *    (&, <, >, ", ' — ampersand first, so escaping is single-pass and never
 *    double-encodes). The artifact is self-contained: no scripts, no anchor
 *    tags, no external resources, no dynamic attributes — workspace content
 *    only ever lands in TEXT positions, already escaped.
 *
 * Copy rules: external audience only (shareable in a PR/channel) — no
 * internal document pointers; terminology per the glossary ("review",
 * "boundary gap" — never scan/vulnerability).
 *
 * Determinism: byte-identical for identical inputs; the caller-supplied
 * `generatedAt` appears on exactly ONE line per format, so two runs over the
 * same workspace differ only on the timestamp line.
 */
